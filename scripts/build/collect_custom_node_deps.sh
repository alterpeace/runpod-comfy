#!/bin/bash
# =============================================================================
# Collect all requirements.txt files from custom_nodes and generate a single
# consolidated requirements file that can be baked into the Docker image.
#
# This eliminates the ~5 minute custom node dependency installation that
# happens on every container creation, reducing cold boot to ~30 seconds.
#
# Usage:
#   ./scripts/build/collect_custom_node_deps.sh                    # from ~/comfy/custom_nodes
#   ./scripts/build/collect_custom_node_deps.sh /path/to/custom_nodes  # custom path
#   ./scripts/build/collect_custom_node_deps.sh --output custom-reqs.txt  # custom output
#
# Then add to Dockerfile:
#   COPY custom-nodes-requirements.txt ./
#   RUN . /comfyui/venv/bin/activate && uv pip install --no-deps -r custom-nodes-requirements.txt
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

# Defaults
CUSTOM_NODES_DIR="${COMFY_DATA_DIR:-$HOME/comfy}/custom_nodes"
OUTPUT_FILE="$PROJECT_DIR/custom-nodes-requirements.txt"

# Parse args
while [[ $# -gt 0 ]]; do
    case "$1" in
        --output)
            OUTPUT_FILE="$2"
            shift 2
            ;;
        --help|-h)
            echo "Usage: $0 [OPTIONS] [CUSTOM_NODES_DIR]"
            echo ""
            echo "Collect all requirements.txt from custom_nodes and generate"
            echo "a consolidated requirements file for Docker build."
            echo ""
            echo "Options:"
            echo "  --output FILE  Output file (default: custom-nodes-requirements.txt)"
            echo "  --help          Show this help"
            echo ""
            echo "Environment:"
            echo "  COMFY_DATA_DIR  Path to ComfyUI data dir (default: ~/comfy)"
            exit 0
            ;;
        *)
            CUSTOM_NODES_DIR="$1"
            shift
            ;;
    esac
done

# Check custom_nodes directory
if [ ! -d "$CUSTOM_NODES_DIR" ]; then
    echo -e "${RED}ERROR: custom_nodes directory not found: $CUSTOM_NODES_DIR${NC}"
    echo -e "${YELLOW}Set COMFY_DATA_DIR or pass the path as an argument${NC}"
    echo -e "${YELLOW}Example: $0 /home/chiral/comfy/custom_nodes${NC}"
    exit 1
fi

echo -e "${BLUE}=== Collecting Custom Node Dependencies ===${NC}"
echo -e "  Source: $CUSTOM_NODES_DIR"
echo -e "  Output: $OUTPUT_FILE"
echo ""

# Collect all requirements.txt files
TEMP_FILE=$(mktemp)
COUNT=0
PACKAGES=""

for req in "$CUSTOM_NODES_DIR"/*/requirements.txt; do
    [ -f "$req" ] || continue
    NODE_NAME=$(basename "$(dirname "$req")")
    COUNT=$((COUNT + 1))
    echo -e "${GREEN}  Found: $NODE_NAME${NC}"

    # Add a comment header for each node's requirements
    echo "" >> "$TEMP_FILE"
    echo "# === $NODE_NAME ===" >> "$TEMP_FILE"

    # Copy requirements, skipping comments and empty lines
    while IFS= read -r line || [ -n "$line" ]; do
        # Skip comments and empty lines
        [[ "$line" =~ ^[[:space:]]*# ]] && continue
        [[ -z "${line// }" ]] && continue
        echo "$line" >> "$TEMP_FILE"
    done < "$req"
done

if [ "$COUNT" -eq 0 ]; then
    echo -e "${YELLOW}No requirements.txt files found in $CUSTOM_NODES_DIR${NC}"
    rm -f "$TEMP_FILE"
    exit 0
fi

# Deduplicate packages (keep first occurrence)
DEDUPED_FILE=$(mktemp)
echo "# Custom Node Dependencies (auto-generated)" > "$DEDUPED_FILE"
echo "# Generated by: scripts/build/collect_custom_node_deps.sh" >> "$DEDUPED_FILE"
echo "# Date: $(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$DEDUPED_FILE"
echo "# Source: $CUSTOM_NODES_DIR" >> "$DEDUPED_FILE"
echo "# Nodes: $COUNT" >> "$DEDUPED_FILE"
echo "" >> "$DEDUPED_FILE"

SEEN_PACKAGES=()
while IFS= read -r line; do
    # Skip comments
    [[ "$line" =~ ^[[:space:]]*# ]] && echo "$line" >> "$DEDUPED_FILE" && continue
    [[ -z "${line// }" ]] && continue

    # Extract package name (before any version specifier)
    PKG_NAME=$(echo "$line" | sed 's/[<>=!~].*//' | sed 's/\[.*\]//' | tr '[:upper:]' '[:lower:]' | xargs)

    # Skip if already seen
    SKIP=false
    for seen in "${SEEN_PACKAGES[@]}"; do
        if [ "$PKG_NAME" = "$seen" ]; then
            SKIP=true
            break
        fi
    done

    if [ "$SKIP" = false ]; then
        SEEN_PACKAGES+=("$PKG_NAME")
        echo "$line" >> "$DEDUPED_FILE"
    fi
done < "$TEMP_FILE"

# Move to final output
mv "$DEDUPED_FILE" "$OUTPUT_FILE"
rm -f "$TEMP_FILE"

# Count unique packages
UNIQUE_COUNT=$(grep -v "^#" "$OUTPUT_FILE" | grep -v "^$" | wc -l)

echo ""
echo -e "${GREEN}=== Done! ===${NC}"
echo -e "  Nodes scanned: $COUNT"
echo -e "  Unique packages: $UNIQUE_COUNT"
echo -e "  Output: $OUTPUT_FILE"
echo ""
echo -e "${BLUE}To bake into Docker image, add to Dockerfile:${NC}"
echo -e "  COPY custom-nodes-requirements.txt ./"
echo -e "  RUN . /comfyui/venv/bin/activate && \\"
echo -e "      uv pip install --no-deps -r custom-nodes-requirements.txt"
echo ""
echo -e "${BLUE}Then set in .env to skip runtime install:${NC}"
echo -e "  AUTO_INSTALL_CUSTOM_NODE_DEPS=false"